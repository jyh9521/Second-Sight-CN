inline std::array<unsigned char,8> encoding(const Site& s,uintptr_t to) {
    std::array<unsigned char,8> bytes{0x90,0x90,0x90,0x90,0x90,0x90,0x90,0x90};
    bytes[0]=s.opcode;
    const auto rel=static_cast<uint32_t>(to-s.va-5);
    for(size_t i=0;i<4;++i) bytes[i+1]=static_cast<unsigned char>(rel>>(i*8));
    return bytes;
}
inline bool keyEdge(bool& prior,bool pressed,bool foreground) {
    const bool edge=foreground && pressed && !prior;
    prior=pressed;
    return edge;
}
